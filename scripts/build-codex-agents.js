#!/usr/bin/env node
/**
 * Generate Codex agent-role files from the Claude Code agent definitions.
 *
 * Claude Code reads agents/<role>.md (YAML frontmatter + markdown body). Codex
 * has no such file type: a subagent role is a TOML config layer referenced from
 * config.toml as `agents.<role>.config_file`. This script keeps the two in step
 * so the prompt of a role is written once, in agents/<role>.md, and the Codex
 * variant is derived — never edited by hand.
 *
 * Output per role: agents/codex/<role>.toml containing `developer_instructions` = the markdown body
 * (frontmatter stripped). Plus agents/codex/config-snippet.toml — the block a
 * project appends to its config.toml to register the roles (the
 * project-onboarding skill pastes it, replacing <PLUGIN_ROOT>). It is a .toml,
 * not a .md, on purpose: Claude Code registers every markdown file under
 * agents/ as an agent definition.
 *
 * Usage: node scripts/build-codex-agents.js        (from the plugin root)
 * Idempotent: re-running with unchanged sources produces identical files.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'agents');
const outDir = path.join(srcDir, 'codex');
const checkOnly = process.argv.includes('--check');
const stale = [];
function writeGenerated(file, text) {
  const target = path.join(outDir, file);
  if (checkOnly) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) stale.push(file);
  } else fs.writeFileSync(target, text, 'utf8');
}

/** Roles inherit the parent model and effort; project-owned overrides remain local. */
const ROLES = {
  developer: {
    description:
      'Developer: spec review for implementability, technical research against official docs, writing code and prototypes per an approved spec. Lean by default, root-cause fixes, evidence with every "done".',
  },
  tester: {
    description:
      'Tester: spec review for testability, verification by actually running code and tests, test strategy. Writes the evidence file the auditor reads. Not run = not verified.',
  },
  critic: {
    description:
      'Critic: adversarial review of a spec, architecture doc, plan or research before the user sees it — unproven assumptions, silent forks, unsourced claims, excess complexity, where it breaks. Findings, never a verdict; never edits the artifact.',
  },
  auditor: {
    description:
      'Auditor: blind audit of a finished change against its contract, given only the change package, the contract and the tester evidence. Never reads plans, journals or git history. Findings, never a verdict; no edits, no execution.',
  },
  researcher: {
    description:
      'Researcher: read-only digest of facts a task needs, each with its source — where code lives, the execution path, similar code, nearby tests, contracts that must not break, relevant project docs/ and official documentation of the locked version; conflicts and gaps. Never edits.',
  },
  debugger: {
    description:
      'Debugger: root cause of a failure by reproduction and one-at-a-time hypotheses; returns evidence and a minimal fix proposal. Runs tests, never edits.',
  },
};


/** Split a markdown file into its YAML frontmatter and body. */
function splitFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!m) throw new Error('no frontmatter');
  return { frontmatter: m[1], body: m[2].replace(/^\s+/, '') };
}

/**
 * TOML literal multi-line strings ('''...''') take no escapes, so Windows
 * paths inside the prompts survive untouched. The only sequence that cannot
 * appear is ''' itself.
 */
function tomlLiteral(s) {
  if (s.includes("'''")) throw new Error("body contains ''' which TOML literal strings cannot hold");
  return "'''\n" + s.replace(/\r\n/g, '\n').trimEnd() + "\n'''";
}

if (!checkOnly) fs.mkdirSync(outDir, { recursive: true });

const snippet = [
  '# Codex agent roles — generated by scripts/build-codex-agents.js from agents/<role>.md',
  '# Do not edit by hand; edit the source and re-run the script.',
  '#',
  '# Codex has no per-plugin agents: a role is a TOML config layer that a project (or the',
  "# user config) registers. Append this block to the project's .codex/config.toml (or",
  '# ~/.codex/config.toml), replacing <PLUGIN_ROOT> with the absolute install path the',
  '# SessionStart hook prints. The project-onboarding skill does this.',
  '',
  // max_depth is omitted: the official config reference does not document agents.max_depth.
  '[agents]',
  'enabled = true',
  '',
];

/**
 * Write agents/codex/<role>.toml and append the role's registration block to
 * the snippet.
 *
 * @param {string} role   role name — file stem and the [agents.<role>] key
 * @param {object} cfg    entry of ROLES (description)
 * @param {string} body   the prompt that becomes `developer_instructions`
 * @param {string} source where the prompt came from, for the file header
 */
function emitRole(role, cfg, body, source) {
  const toml = [
    `# Generated from ${source} by scripts/build-codex-agents.js — do not edit by hand.`,
    `# Register in config.toml as: [agents.${role}] config_file = "<PLUGIN_ROOT>/agents/codex/${role}.toml"`,
    '',
    `developer_instructions = ${tomlLiteral(body)}`,
    '',
  ].join('\n');
  writeGenerated(`${role}.toml`, toml);

  snippet.push(
    `[agents.${role}]`,
    `config_file = "<PLUGIN_ROOT>/agents/codex/${role}.toml"`,
    `description = "${cfg.description.replace(/"/g, '\\"')}"`,
    ''
  );
}

// The prompt of every role is the markdown body of agents/<role>.md.
for (const role of Object.keys(ROLES)) {
  const src = fs.readFileSync(path.join(srcDir, `${role}.md`), 'utf8');
  const { body } = splitFrontmatter(src);
  emitRole(role, ROLES[role], body, `agents/${role}.md`);
}

writeGenerated('config-snippet.toml', snippet.join('\n'));
// Every markdown role needs a ROLES entry, and every generated file a source: a new
// agents/<role>.md must not silently lack a Codex role, a removed one must not linger.
const sources = fs.readdirSync(srcDir).filter((f) => f.endsWith('.md')).map((f) => f.replace(/\.md$/, ''));
for (const role of sources) if (!ROLES[role]) stale.push(`agents/${role}.md has no ROLES entry`);
for (const f of fs.readdirSync(outDir)) {
  if (f.endsWith('.toml') && f !== 'config-snippet.toml' && !ROLES[f.replace(/\.toml$/, '')]) stale.push(`orphaned agents/codex/${f}`);
}
if (stale.length) { console.error('regenerate Codex roles: ' + stale.join(', ')); process.exit(1); }

const roleCount = Object.keys(ROLES).length;
console.log(`${checkOnly ? 'checked' : 'wrote'} ${roleCount} role files + config-snippet.toml to ${outDir}`);
